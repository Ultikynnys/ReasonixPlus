#!/usr/bin/env node
/**
 * Generates packages/core-utils/src/providers.generated.ts from providers/*.json.
 *
 * The barrel exists because JSON imports widen to `string` (so a literal
 * ProviderID union cannot be inferred from the JSON) and because the shared
 * registry is bundled into the desktop webview, where a runtime directory read
 * is impossible. `renderRegistry()` is exported so the drift test can compare
 * the committed file against a fresh render.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const defaultProvidersDir = join(repoRoot, "packages/core-utils/src/providers");
const defaultOutputPath = join(repoRoot, "packages/core-utils/src/providers.generated.ts");

/** A provider identifier as a JS binding: `deepseek` → `deepseek`, `my-provider` → `my_provider`. */
function importName(id, taken) {
  const base = /^[A-Za-z_$]/.test(id) ? id : `provider_${id}`;
  let name = base.replace(/[^A-Za-z0-9_$]/g, "_");
  if (taken.has(name)) name = `${name}_${taken.size}`;
  taken.add(name);
  return name;
}

/** Reads every providers/*.json, sorted by file name, failing loudly per file. */
export function readProviderDocuments(dir = defaultProvidersDir) {
  const files = readdirSync(dir)
    .filter((name) => name.endsWith(".json"))
    .sort();
  return files.map((file) => {
    let document;
    try {
      document = JSON.parse(readFileSync(join(dir, file), "utf8"));
    } catch (error) {
      throw new Error(`providers/${file}: ${error instanceof Error ? error.message : error}`);
    }
    return { file, id: file.replace(/\.json$/, ""), document };
  });
}

/** Routable ids in display order — the source of `ProviderID`. */
function routableIds(entries) {
  return entries
    .filter((entry) => typeof entry.document?.providerId === "string")
    .sort(
      (a, b) =>
        Number(a.document.order ?? 0) - Number(b.document.order ?? 0) || a.id.localeCompare(b.id),
    )
    .map((entry) => entry.document.providerId);
}

/** Renders providers.generated.ts as text. */
export function renderRegistry(dir = defaultProvidersDir) {
  const entries = readProviderDocuments(dir);
  if (entries.length === 0) throw new Error(`no provider JSON files in ${dir}`);
  const taken = new Set();
  const bindings = entries.map((entry) => ({ ...entry, binding: importName(entry.id, taken) }));
  const imports = bindings
    .map(({ binding, id }) => `import ${binding} from "./providers/${id}.json";`)
    .join("\n");
  const documents = bindings
    .map(({ binding, file }) => `  { file: ${JSON.stringify(file)}, document: ${binding} },`)
    .join("\n");
  const ids = routableIds(bindings)
    .map((id) => `  ${JSON.stringify(id)},`)
    .join("\n");

  return `// Generated by scripts/generate-provider-registry.mjs — do not edit by hand.
// Run \`npm run providers:sync\` after adding or removing a providers/*.json file.

${imports}

/** A provider document and the file it came from. */
export interface ProviderDocumentSource {
  /** File name under providers/, e.g. \`deepseek.json\`. */
  file: string;
  document: unknown;
}

/** Every provider document, one per providers/*.json file, sorted by file name. */
export const PROVIDER_DOCUMENTS: readonly ProviderDocumentSource[] = [
${documents}
];

/** Routable provider ids, derived from each document's \`providerId\` in display order. */
export const PROVIDER_IDS = [
${ids}
] as const;

export type ProviderID = (typeof PROVIDER_IDS)[number];
`;
}

function main() {
  const text = renderRegistry();
  writeFileSync(defaultOutputPath, text);
  const count = readProviderDocuments().length;
  console.log(`Synced ${count} provider files → ${defaultOutputPath}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
